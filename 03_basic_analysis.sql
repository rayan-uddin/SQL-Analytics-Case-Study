-- Q1. Return the Number of Customers in the Database
select count(customer_id) as total_customers from customers;

-- Q2. How many customers are there in each customer_segment?

select 
	customer_segment as Cusotmer_Segment, 
    count(Customer_Id) Number_Of_Customers
from customers
group by customer_segment;

-- Q3. number of customers in each state.

select 
	City as State, 
	count(customer_id) as number_of_Customers
from 
	customers
group by 
	city
order by number_of_Customers desc;
    
-- Q4. products in each product category

SELECT 
    Category, COUNT(Product_Id) AS product_count
FROM
    products
GROUP BY Category
ORDER BY product_count DESC;

-- Q5. Average Product Price in each category

SELECT 
    Category, AVG(Price) AS Average_Price
FROM
    products
GROUP BY category;

-- Q6. how many orders exist for each order_status.

SELECT 
    Order_Status, COUNT(order_id) Order_Count
FROM
    orders
GROUP BY order_status
ORDER BY Order_Count DESC;

-- Q7. total number of orders where the status is Completed.

SELECT 
    Order_Status, COUNT(order_id) Order_Count
FROM
    orders
GROUP BY order_status
having Order_Status = 'Completed';

-- Q8. Calculate the total revenue generated from Completed orders only.
SELECT
    sum(Unit_price * Quantity) as Total_Revenue
FROM
    orders
where Order_Status = 'Completed';

-- Q9. Calculate the total revenue generated by each product category for Completed orders only.
SELECT 
    p.Category, sum(o.Unit_price * o.Quantity) as Total_Revenue
FROM
    orders AS o
LEFT JOIN products AS p 
	ON o.Product_ID = p.Product_Id
group by p.Category;

-- Q10. Find customers whose total spending on Completed orders is greater than 15,000.

SELECT
    c.customer_id,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    SUM(o.quantity * o.unit_price) AS total_spending
FROM customers AS c
JOIN orders AS o
    ON c.customer_id = o.customer_id
WHERE o.order_status = 'Completed'
GROUP BY
    c.customer_id,
    c.first_name,
    c.last_name
having total_spending > 15000;